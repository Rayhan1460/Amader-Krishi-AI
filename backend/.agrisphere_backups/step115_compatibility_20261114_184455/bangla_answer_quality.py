def _normalize(value):
    return "".join(str(value or "").lower().split()).replace("?", "").replace("।", "")


# STEP_110_FISH_NEGATION_GUARD
def _fish_surface_negated(q):
    negative_forms = (
        "উঠেআসছেনা",
        "উঠেআসেনা",
        "উঠছেনা",
        "উঠেনা",
        "ওঠেনা",
        "উঠেনি",
        "ভাসছেনা",
        "ভাসেনা",
        "হাঁসফাঁসকরছেনা",
        "হাঁসফাঁসকরেনা",
        "হাপাচ্ছেনা",
        "হাঁপাচ্ছেনা",
    )

    if not any(x in q for x in negative_forms):
        return False

    for connector in ("কিন্তু", "তবে", "অথচ"):
        if connector not in q:
            continue

        tail = q.rsplit(connector, 1)[-1]

        positive_forms = (
            "উঠছে",
            "উঠেআসছে",
            "ভাসছে",
            "হাঁসফাঁসকরছে",
            "হাপাচ্ছে",
            "হাঁপাচ্ছে",
        )

        if (
            any(x in tail for x in positive_forms)
            and not any(x in tail for x in negative_forms)
        ):
            return False

    return True


